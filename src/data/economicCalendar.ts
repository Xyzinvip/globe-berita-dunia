export function getEconomicEventsForCountry(countryName: string, currency?: string): EconomicEvent[] {
  return ECONOMIC_EVENTS.filter((e) => {
    if (e.countryName.toLowerCase() === countryName.toLowerCase()) return true;
    if (currency && e.currency.toUpperCase() === currency.toUpperCase()) return true;
    // Map Euro countries
    const euroCountries = ['Germany', 'France', 'Italy', 'Spain', 'Netherlands', 'Belgium', 'Austria', 'Ireland', 'Portugal', 'Finland', 'Greece'];
    if (e.currency === 'EUR' && euroCountries.includes(countryName)) return true;
    return false;
  });
}
