export function getCountryFlag(name: string): string {
  if (COUNTRIES_DATA[name]) return COUNTRIES_DATA[name].flag;
  for (const c of Object.values(COUNTRIES_DATA)) {
    if (c.name.toLowerCase() === name.toLowerCase() || c.nameId.toLowerCase() === name.toLowerCase()) {
      return c.flag;
    }
  }
  return '🌍';
}

export function getCountryInfo(
  name: string,
  id?: string,
  customCenter?: [number, number]
): CountryInfo {
  // 1. Direct match by exact key
  if (COUNTRIES_DATA[name]) {
    const base = COUNTRIES_DATA[name];
    if (customCenter && isFinite(customCenter[0]) && isFinite(customCenter[1]) && !base.center) {
      return { ...base, center: customCenter };
    }
    return base;
  }

  // 2. Case-insensitive or localized name match
  const lower = (name || '').toLowerCase().trim();
  const byName = Object.values(COUNTRIES_DATA).find(
    (c) =>
      c.name.toLowerCase() === lower ||
      c.nameId.toLowerCase() === lower ||
      (c.code && c.code.toLowerCase() === lower)
  );
  if (byName) {
    return byName;
  }

  // Common aliases
  if (lower === 'yaman') return COUNTRIES_DATA['Yemen'];
  if (lower === 'as' || lower === 'usa' || lower === 'amerika' || lower === 'amerika serikat') return COUNTRIES_DATA['United States of America'];
  if (lower === 'uk' || lower === 'inggris' || lower === 'inggris raya' || lower === 'britania') return COUNTRIES_DATA['United Kingdom'];
  if (lower === 'tiongkok' || lower === 'cina') return COUNTRIES_DATA['China'];
  if (lower === 'rusia') return COUNTRIES_DATA['Russia'];
  if (lower === 'jerman') return COUNTRIES_DATA['Germany'];
  if (lower === 'prancis') return COUNTRIES_DATA['France'];
  if (lower === 'jepang') return COUNTRIES_DATA['Japan'];
  if (lower === 'korsel' || lower === 'korea selatan') return COUNTRIES_DATA['South Korea'];
  if (lower === 'uea' || lower === 'uni emirat arab') return COUNTRIES_DATA['United Arab Emirates'];

  // 3. Fallback with valid custom center
  const centerCoords: [number, number] =
    customCenter && isFinite(customCenter[0]) && isFinite(customCenter[1])
      ? customCenter
      : [0, 20];

  return {
    id: id || '000',
    name: name,
    nameId: name,
    flag: '🌍',
    code: name.slice(0, 2).toUpperCase(),
    capital: 'Pusat Wilayah ' + name,
    continent: 'Global',
    population: 'Populasi Global',
    currency: 'Mata Uang Nasional',
    timezone: 'Waktu Lokal',
    center: centerCoords,
    languages: 'Resmi',
  };
}
